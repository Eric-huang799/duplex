const { app, BrowserWindow, WebContentsView, ipcMain } = require('electron')
const path = require('node:path')
app.setPath('userData', process.argv[2])
app.commandLine.appendSwitch('remote-debugging-port', '0')
app.commandLine.appendSwitch('remote-debugging-address', '127.0.0.1')
app.commandLine.appendSwitch('disable-renderer-backgrounding')
app.commandLine.appendSwitch('disable-backgrounding-occluded-windows')
app.commandLine.appendSwitch('disable-background-timer-throttling')
app.whenReady().then(async () => {
  const win = new BrowserWindow({ show: false, width: 900, height: 700, webPreferences: { offscreen: true } })
  ipcMain.on('overlay:event', (_event, payload) => console.log('DUPLEX_EVENT ' + JSON.stringify(payload)))
  const view = new WebContentsView({ webPreferences: { preload: process.argv[3], contextIsolation: true, sandbox: true, backgroundThrottling: false, offscreen: true } })
  win.contentView.addChildView(view)
  view.setBounds({ x: 0, y: 0, width: 900, height: 700 })
  await view.webContents.loadFile(path.join(__dirname, 'playwright-page-fixture.html'))
  view.webContents.debugger.attach('1.3')
  const info = await view.webContents.debugger.sendCommand('Target.getTargetInfo')
  console.log('DUPLEX_FIXTURE ' + JSON.stringify(info.targetInfo))
  process.stdin.on('data', () => app.quit())
})
